// ダミーの対応付け・反映境界をNode標準機能だけで検証。
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { previewExcel, applyExcel, REASONS } from '../standalone/excel-import.js';
const read = name => JSON.parse(readFileSync(new URL(`./fixtures/f31/${name}`, import.meta.url)));
const data = read('dummy-data.json'), rows = read('dummy-rows.json');
const before = JSON.stringify(data);
const preview = previewExcel(rows, 'DUMMY-P31', data.runs, data.regs, data.cert);
assert.equal(preview.project, 'DUMMY-P31');
assert.equal(preview.accepted.length, 8);
assert.equal(preview.rejected.length, 9);
assert.deepEqual(new Set(preview.rejected.map(r => r.reason)), new Set(Object.values(REASONS)));
assert.equal(preview.accepted.filter(r => r.status === '追加').length, 6);
assert.equal(preview.accepted.filter(r => r.status === '既存と同じ').length, 1);
assert.equal(preview.accepted.filter(r => r.status === '既存と違う').length, 1);
assert.equal(preview.accepted.filter(r => r.mark === '01で取得').length, 3);
assert.equal(JSON.stringify(data), before, 'B4: 解析はデータを変更しない');
const cert = applyExcel(data.cert, preview);
assert.equal(cert.length, 8);
for (const existing of data.cert.filter(c => c.ck)) assert.deepEqual(cert.find(c => c.runKey === existing.runKey && c.rid === existing.rid), existing);
assert.ok(cert.find(c => c.runKey === 'r301' && c.rid === 'g301').planned, '予定フラグは保持');
assert.ok(!cert.some(c => ['r304','r305','r306','r307'].includes(c.runKey)), 'B2/B3');
assert.ok(!cert.some(c => ['g303','g305','g306','g308'].includes(c.rid)), 'B1/B6');
assert.ok(cert.every(c => c.ck), 'B1 空番号は反映しない');
assert.strictEqual(applyExcel(cert, preview), cert, '再反映で既存番号を変更しない');
assert.equal(JSON.stringify(data), before, '入力は反映後も不変');
const newer = [{row: 1, number: 'E43*156R00/00*9999*00', types: 'DUMMY-A'}];
assert.deepEqual(previewExcel(newer,'DUMMY-P31',data.runs,data.regs,[]).accepted.map(r => r.reg), ['R156-00']);
const noValidID = data.regs.map(r => ({...r,id:'DEMO-'+r.id}));
assert.equal(previewExcel(newer,'DUMMY-P31',data.runs,noValidID,[]).rejected[0].reason, REASONS.noReg);
console.log('PASS A1–A6 / B1–B6: 対応付け、全9理由、部分展開、幅と空白、競合排除、非破壊反映');
